#!/usr/bin/env python3
"""Emit a deterministic F06 Host-only test feed. No hidden science data is compiled."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

KINDS = {"star":12,"planet":13,"moon":14,"nebula":15,"station":16,"asteroid":17,"starship":1,"shuttle":2,"probe":3}
FIELDS = ("position_milli_au", "active", "world_exit_evidence", "strength_permille", "interference_permille")

def build(source: Path) -> str:
    data = json.loads(source.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1 or data.get("status") != "FIXTURE_NON_CANON_NOT_A_PERSISTENT_GALAXY":
        raise ValueError("only the non-canonical F06 QA fixture is supported")
    ticks = data["time_frames_seconds"]
    if (len(ticks) > 32 or sorted(set(ticks)) != ticks or
            not {0, 3600, 7200, 14400, 28800}.issubset(ticks) or
            ticks[-1] != 28800):
        raise ValueError("invalid ordered eight-hour observation schedule")
    entities = data["entities"]
    if not (15 <= len(entities) <= 48):
        raise ValueError("small bounded system required")
    keys = [e["key"] for e in entities]
    if len(set(keys)) != len(keys) or any(not isinstance(x, int) or x <= 0 for x in keys):
        raise ValueError("duplicate or invalid world entity keys")
    parent_lookup = {e["key"]: e for e in entities}
    for e in entities:
        if e["kind"] not in KINDS or e["visual_asset_id"] is not None:
            raise ValueError("unknown signature category or unapproved visual asset")
        if e["kind"] in ("star", "planet", "moon", "nebula", "asteroid") and e["ship_class_id"] != 0:
            raise ValueError("celestial class must never reuse ship class numeric IDs")
        if e["kind"] == "moon" and parent_lookup.get(e.get("parent_key"), {}).get("kind") != "planet":
            raise ValueError("orphan moon")
        if any(not isinstance(v, int) or abs(v) > 100000000 for v in e["position_milli_au"]):
            raise ValueError("out-of-range coordinates")
        if e["kind"] == "planet" and not e.get("science_truth", {}).get("planet_class"):
            raise ValueError("planet fixture needs separate host-only classification")
        if e["kind"] == "starship" and e["ship_class_id"] not in (6, 8, 16, 18):
            raise ValueError("every uncamouflaged QA starship must have a valid class")
        if e["kind"] == "shuttle" and e["ship_class_id"] != 13:
            raise ValueError("QA shuttle must have an identified design")
        if not (0 <= e["strength_permille"] <= 1000 and 0 <= e["interference_permille"] <= 550):
            raise ValueError("non-normalized sensor signature")
        seen_ticks = set()
        for change in e["updates"]:
            t = change["tick"]
            if t not in ticks[1:] or t in seen_ticks or any(k not in FIELDS + ("tick",) for k in change):
                raise ValueError("unknown or duplicate scripted event")
            seen_ticks.add(t)
    origin = data["observation_ship"]["absolute_position_milli_au"]
    if len(origin) != 3 or data["observation_ship"]["sensor_profile_id"] != 5:
        raise ValueError("invalid observation ship setup")
    text = [
        "// GENERATED by build_validation_system.py. Test-only authoritative world frames.",
        "// Contains NO planet composition, class M classification, names or 3D asset data.",
        "#pragma once",
        "#include \"f06_sensors.h\"",
        "#include <cstdint>",
        "struct F06DemoFrame { uint64_t tick, source_revision, count; const F06WorldEntity* entities; };",
    ]
    for index, tick in enumerate(ticks):
        text.append(f"inline constexpr F06WorldEntity F06_DEMO_ENTITIES_{index}[] = {{")
        for e in sorted(entities, key=lambda e: e["key"]):
            state = dict(e)
            for change in sorted(e["updates"], key=lambda x: x["tick"]):
                if change["tick"] <= tick:
                    state.update({k: v for k, v in change.items() if k != "tick"})
            x, y, z = state["position_milli_au"]
            values = [state["key"], x, y, z, state["transponder_id"], state["ship_class_id"],
                      state["strength_permille"], state["interference_permille"], state["active"],
                      state["world_exit_evidence"], KINDS[state["kind"]]]
            if any(abs(a - b) > 100000000 for a, b in zip((x, y, z), origin)):
                raise ValueError("observer-relative position out of range")
            if state["active"] not in (0, 1) or not 0 <= state["world_exit_evidence"] <= 3:
                raise ValueError("bad active/exit evidence")
            text.append("  {" + ", ".join(str(v) for v in values) + "},")
        text.append("};")
    text.append("inline constexpr F06DemoFrame F06_DEMO_FRAMES[] = {")
    for index, tick in enumerate(ticks):
        text.append(f"  {{{tick}, {1001 + index}, sizeof(F06_DEMO_ENTITIES_{index}) / sizeof(F06WorldEntity), F06_DEMO_ENTITIES_{index}}},")
    text.extend(["};", f"inline constexpr int64_t F06_DEMO_OBSERVER_X = {origin[0]};",
                 f"inline constexpr int64_t F06_DEMO_OBSERVER_Y = {origin[1]};",
                 f"inline constexpr int64_t F06_DEMO_OBSERVER_Z = {origin[2]};", ""])
    return "\n".join(text)

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    out = build(args.source)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(out, encoding="utf-8")

if __name__ == "__main__":
    main()
